import { Router } from 'express';
import { authRoutes } from './authRoutes.js';
import { produtoRoutes } from './produtoRoutes.js';
import { pedidoRoutes } from './pedidoRoutes.js';
import { ProdutoController } from '../controllers/ProdutoController.js';
import { privacidadeRoutes } from './privacidadeRoutes.js';
import { PrivacidadeController } from '../controllers/PrivacidadeController.js';
import { authMiddleware } from '../middlewares/authMiddleware.js';
export const router = Router();
router.use('/auth', authRoutes);
router.use('/produtos', produtoRoutes);
router.use('/pedidos', pedidoRoutes);
router.use('/privacidade', privacidadeRoutes);
router.get('/auditoria', authMiddleware(['ADMIN']), PrivacidadeController.auditoria);
router.get('/unidades', ProdutoController.unidades);
router.get('/health', (_req, res) => res.json({ status: 'ok' }));
